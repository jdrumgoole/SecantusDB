/// A WiredTiger database connection. One per process (sessions are per-thread).
pub struct Connection {
    ptr: *mut sys::WT_CONNECTION,
    /// The connection keeps statistics (`statistics=(fast)` or more): its
    /// sessions' can be read ([`Session::statistics`]).
    stats: bool,
    /// The event handler WiredTiger was given. It writes its defaults into
    /// the callbacks left null, so the handler is the connection's own and
    /// outlives it: `Drop` closes the connection before this field drops.
    _handler: Box<sys::WT_EVENT_HANDLER>,
}

// The connection handle is safe to share across threads; WiredTiger's own MVCC
// and per-session affinity provide the actual thread-safety.
unsafe impl Send for Connection {}
unsafe impl Sync for Connection {}

/// WiredTiger's error callback. A panic ends the process, as mongod's
/// handler does (`fassert` on `WT_PANIC`): after one every storage call
/// fails while `hello` still answers, and a supervisor watching for the
/// process to die never sees it (RM-188). Any other error returns non-zero,
/// which leaves WiredTiger to print it as it would with no handler.
unsafe extern "C" fn handle_error(
    _handler: *mut sys::WT_EVENT_HANDLER,
    _session: *mut sys::WT_SESSION,
    error: std::os::raw::c_int,
    message: *const std::os::raw::c_char,
) -> std::os::raw::c_int {
    if error == sys::WT_PANIC {
        let text = if message.is_null() {
            String::from("(no message)")
        } else {
            // SAFETY: WiredTiger passes a NUL-terminated message.
            unsafe { std::ffi::CStr::from_ptr(message) }
                .to_string_lossy()
                .into_owned()
        };
        eprintln!("secantus-wt: WiredTiger panic, aborting: {text}");
        std::process::abort();
    }
    1
}

/// The event handler a connection is opened with: only the error callback
/// is ours, and WiredTiger fills in its defaults for the rest -- writing
/// them into the struct, which is why it cannot be a `static`.
fn event_handler() -> Box<sys::WT_EVENT_HANDLER> {
    Box::new(sys::WT_EVENT_HANDLER {
        handle_error: Some(handle_error),
        handle_message: None,
        handle_progress: None,
        handle_close: None,
        handle_general: None,
    })
}

/// Whether a connection opened with `config` keeps statistics: its
/// `statistics=(...)` names a level other than `none` (WiredTiger's
/// default is none). A statistics cursor on a connection that keeps none
/// is refused (`EINVAL`).
fn keeps_statistics(config: &str) -> bool {
    let Some(at) = config.find("statistics=(") else {
        return false;
    };
    let rest = &config[at + "statistics=(".len()..];
    let levels = rest.split(')').next().unwrap_or("");
    levels
        .split(',')
        .map(str::trim)
        .any(|l| matches!(l, "all" | "fast" | "cache_walk" | "tree_walk"))
}

impl Connection {
    /// Open (creating if needed) a WiredTiger database rooted at `home` with the
    /// given config string (e.g. `"create,cache_size=256M,log=(enabled=true)"`).
    pub fn open(home: &str, config: &str) -> Result<Connection> {
        let home_c = CString::new(home).map_err(nul_err)?;
        let cfg_c = CString::new(config).map_err(nul_err)?;
        let mut ptr: *mut sys::WT_CONNECTION = ptr::null_mut();
        let mut handler = event_handler();
        check(unsafe {
            sys::wiredtiger_open(home_c.as_ptr(), &mut *handler, cfg_c.as_ptr(), &mut ptr)
        })?;
        Ok(Connection {
            ptr,
            stats: keeps_statistics(config),
            _handler: handler,
        })
    }

    /// Open a new session (thread-affine — open one per thread).
    pub fn open_session(&self) -> Result<Session> {
        let open = unsafe { (*self.ptr).open_session }.unwrap();
        let mut sptr: *mut sys::WT_SESSION = ptr::null_mut();
        check(unsafe { open(self.ptr, ptr::null_mut(), ptr::null(), &mut sptr) })?;
        Ok(Session {
            ptr: sptr,
            cursor_config: None,
            in_txn: Cell::new(false),
            txn_end: RefCell::new(Vec::new()),
            stats: self.stats,
            stats_cursor: RefCell::new(None),
        })
    }
}

impl Connection {
    /// `WT_CONNECTION::set_timestamp`, e.g. `"oldest_timestamp=1a2b"` (hex).
    pub fn set_timestamp(&self, config: &str) -> Result<()> {
        let f = unsafe { (*self.ptr).set_timestamp }.unwrap();
        let cfg_c = CString::new(config).map_err(nul_err)?;
        check(unsafe { f(self.ptr, cfg_c.as_ptr()) })
    }

    /// `WT_CONNECTION::query_timestamp`, e.g. `"get=oldest_timestamp"`: the
    /// timestamp in hex, "0" when it has not been set.
    pub fn query_timestamp(&self, config: &str) -> Result<String> {
        let f = unsafe { (*self.ptr).query_timestamp }.unwrap();
        let cfg_c = CString::new(config).map_err(nul_err)?;
        let mut buf = [0 as c_char; 64];
        check(unsafe { f(self.ptr, buf.as_mut_ptr(), cfg_c.as_ptr()) })?;
        Ok(unsafe { CStr::from_ptr(buf.as_ptr()) }
            .to_string_lossy()
            .into_owned())
    }
}

impl Drop for Connection {
    fn drop(&mut self) {
        if !self.ptr.is_null() {
            if let Some(close) = unsafe { (*self.ptr).close } {
                // A drop cannot return the error; it must not vanish (RM-189).
                let rc = unsafe { close(self.ptr, ptr::null()) };
                if rc != 0 {
                    eprintln!("secantus-wt: Connection close failed: {:?}", check(rc));
                }
            }
            self.ptr = ptr::null_mut();
        }
    }
}

