//! `ALTER SYSTEM`, and the configuration file it writes: PostgreSQL's
//! `postgresql.auto.conf`, kept as PostgreSQL keeps it.
//!
//! - The file lives in the store's directory (the data directory) and is
//!   written at once, atomically (a temporary file, synced, renamed over
//!   it), with PostgreSQL's header and one `name = 'value'` line per
//!   setting. `ALTER SYSTEM SET` drops the name's line and adds one at the
//!   end; `RESET` drops it; `RESET ALL` empties the file.
//! - Nothing takes effect when the file is written. The server reads it at
//!   its start and again on `pg_reload_conf()` (the postmaster's SIGHUP):
//!   [`loaded`] is what it read last. A session takes the new values at its next message, as a backend
//!   processes the SIGHUP the postmaster forwards: each value whose source
//!   ranks no higher than the file's changes, so a session's own `SET`, and
//!   a database's or role's default, stay. A parameter only a restart
//!   changes keeps its value and reads `pending_restart`.
//! - `pg_file_settings` reads the file as it is now, whether loaded or not.
//!
//! This server has no `postgresql.conf`: the file's settings sit above the
//! built-in defaults and below everything else, as the auto file does in
//! PostgreSQL.

use std::path::{Path, PathBuf};
use std::sync::{Mutex, OnceLock, Weak};

use super::*;

/// The file's name in the data directory.
const AUTO_CONF: &str = "postgresql.auto.conf";

/// What `write_auto_conf_file` writes first.
const HEADER: &str =
    "# Do not edit this file manually!\n# It will be overwritten by the ALTER SYSTEM command.\n";

/// The parameters ALTER SYSTEM refuses beside the `internal` ones: those
/// PostgreSQL marks `GUC_DISALLOW_IN_FILE` or `GUC_DISALLOW_IN_AUTO_FILE`
/// (measured on 15.19: each is 55P02 "cannot be changed").
const DISALLOWED: [&str; 10] = [
    "config_file",
    "data_directory",
    "is_superuser",
    "role",
    "seed",
    "session_authorization",
    "ssl_renegotiation_limit",
    "transaction_deferrable",
    "transaction_isolation",
    "transaction_read_only",
];

/// One setting line of a configuration file.
#[derive(Clone, Debug, PartialEq)]
pub(crate) struct FileEntry {
    /// As written.
    pub name: String,
    pub value: String,
    /// The file it is in, absolute.
    pub file: Arc<str>,
    pub line: i32,
    /// Its place in the order the files were read.
    pub seq: usize,
}

/// A line the parser could not read, or a file it could not open.
#[derive(Clone, Debug, PartialEq)]
pub(crate) struct FileError {
    pub file: Arc<str>,
    pub line: i32,
    pub message: String,
    pub seq: usize,
}

/// One store's configuration as the server last read it. The store is held
/// weakly, as the transaction ids' is (`xids`): this table must never keep
/// a store open past its server's shutdown.
struct Cluster {
    storage: Weak<Storage>,
    loaded: Arc<Vec<FileEntry>>,
    /// What the server read at its start: the values of the parameters
    /// only a restart changes, which every session runs with.
    at_start: Arc<Vec<FileEntry>>,
    /// The postmaster's `pending_restart` flags, which a new session
    /// inherits.
    pending: Arc<std::collections::HashSet<String>>,
}

/// Moves on with every reload of any store, so a session can tell without
/// a lock that no reload has happened since it last looked.
static EPOCH: std::sync::atomic::AtomicU64 = std::sync::atomic::AtomicU64::new(1);

/// The reload epoch: read it before [`loaded`], so a reload in between is
/// seen at the next look.
pub(crate) fn epoch() -> u64 {
    EPOCH.load(std::sync::atomic::Ordering::Acquire)
}

fn clusters() -> &'static Mutex<HashMap<usize, Cluster>> {
    static C: OnceLock<Mutex<HashMap<usize, Cluster>>> = OnceLock::new();
    C.get_or_init(|| Mutex::new(HashMap::new()))
}

/// The store's directory, made absolute as PostgreSQL's `DataDir` is: the
/// data directory.
pub(crate) fn data_directory(storage: &Storage) -> PathBuf {
    let home = Path::new(storage.home());
    std::fs::canonicalize(home).unwrap_or_else(|_| home.to_path_buf())
}

/// The auto file's path.
pub(crate) fn path(storage: &Storage) -> PathBuf {
    data_directory(storage).join(AUTO_CONF)
}

/// The main configuration file's path (`config_file`).
pub(crate) fn config_file(storage: &Storage) -> PathBuf {
    data_directory(storage).join("postgresql.conf")
}

/// How deep `include` may nest (`ParseConfigFile`'s limit).
const MAX_DEPTH: usize = 10;

/// What the files hold, in the order PostgreSQL reads them: the main
/// configuration file (when the store has one) with what it includes, then
/// the auto file. Settings and the lines that did not parse.
pub(crate) fn read(storage: &Storage) -> std::io::Result<(Vec<FileEntry>, Vec<FileError>)> {
    let mut out = (Vec::new(), Vec::new());
    let mut seq = 0;
    let main = config_file(storage);
    if main.exists() {
        read_file(&main, 0, false, &mut seq, &mut out)?;
    }
    read_file(&path(storage), 0, true, &mut seq, &mut out)?;
    Ok(out)
}

/// The auto file's settings alone, which ALTER SYSTEM rewrites.
fn read_auto(storage: &Storage) -> std::io::Result<Vec<FileEntry>> {
    let mut out = (Vec::new(), Vec::new());
    read_file(&path(storage), 0, true, &mut 0, &mut out)?;
    Ok(out.0)
}

/// One file's settings, with what its `include`, `include_if_exists` and
/// `include_dir` lines name, relative to its directory.
fn read_file(
    file: &Path,
    depth: usize,
    missing_ok: bool,
    seq: &mut usize,
    out: &mut (Vec<FileEntry>, Vec<FileError>),
) -> std::io::Result<()> {
    let shown: Arc<str> = Arc::from(file.display().to_string());
    let text = match std::fs::read_to_string(file) {
        Ok(text) => text,
        Err(e) if e.kind() == std::io::ErrorKind::NotFound && missing_ok => return Ok(()),
        Err(e) => return Err(e),
    };
    let dir = file.parent().map(Path::to_path_buf).unwrap_or_default();
    let (mut entries, mut errors) = parse(&text, &shown);
    // A file is abandoned at its first syntax error, as `ParseConfigFp`
    // gives up when it reports at DEBUG level -- which is how both
    // `pg_file_settings` and a reload that will apply nothing see it.
    if let Some(first) = errors.first().map(|e| e.line) {
        entries.retain(|e| e.line < first);
        errors.truncate(1);
    }
    let mut errors = errors.into_iter().peekable();
    for e in entries {
        while errors.peek().is_some_and(|x| x.line < e.line) {
            let mut x = errors.next().expect("peeked");
            x.seq = *seq;
            *seq += 1;
            out.1.push(x);
        }
        let directive = e.name.to_ascii_lowercase();
        if matches!(
            directive.as_str(),
            "include" | "include_if_exists" | "include_dir"
        ) {
            let target = dir.join(&e.value);
            let fail =
                |message: String, seq: &mut usize, out: &mut (Vec<FileEntry>, Vec<FileError>)| {
                    out.1.push(FileError {
                        file: Arc::clone(&shown),
                        line: e.line,
                        message,
                        seq: *seq,
                    });
                    *seq += 1;
                };
            if depth + 1 > MAX_DEPTH {
                fail(
                    format!(
                        "could not open configuration file \"{}\": maximum nesting depth exceeded",
                        target.display()
                    ),
                    seq,
                    out,
                );
                continue;
            }
            match directive.as_str() {
                "include_dir" => {
                    let mut files: Vec<PathBuf> = match std::fs::read_dir(&target) {
                        Ok(dir) => dir
                            .filter_map(|d| d.ok().map(|d| d.path()))
                            .filter(|p| {
                                p.extension().is_some_and(|x| x == "conf")
                                    && p.file_name()
                                        .and_then(|n| n.to_str())
                                        .is_some_and(|n| !n.starts_with('.'))
                            })
                            .collect(),
                        Err(err) => {
                            fail(
                                format!(
                                    "could not open configuration directory \"{}\": {err}",
                                    target.display()
                                ),
                                seq,
                                out,
                            );
                            continue;
                        }
                    };
                    files.sort();
                    for f in files {
                        read_file(&f, depth + 1, false, seq, out)?;
                    }
                }
                _ => {
                    let if_exists = directive == "include_if_exists";
                    if let Err(err) = read_file(&target, depth + 1, if_exists, seq, out) {
                        fail(
                            format!(
                                "could not open configuration file \"{}\": {err}",
                                target.display()
                            ),
                            seq,
                            out,
                        );
                    }
                }
            }
            continue;
        }
        out.0.push(FileEntry { seq: *seq, ..e });
        *seq += 1;
    }
    for mut x in errors {
        x.seq = *seq;
        *seq += 1;
        out.1.push(x);
    }
    Ok(())
}

/// What the server read from the file at its start or last reload.
pub(crate) fn loaded(storage: &Arc<Storage>) -> Arc<Vec<FileEntry>> {
    let key = Arc::as_ptr(storage) as usize;
    let mut map = clusters().lock().unwrap_or_else(|e| e.into_inner());
    let current = map.get(&key).is_some_and(|c| {
        c.storage
            .upgrade()
            .is_some_and(|s| Arc::ptr_eq(&s, storage))
    });
    if !current {
        // The server's start. A file it cannot read is reported and
        // skipped, as the postmaster logs a bad configuration file and runs
        // on its defaults.
        let entries = match read(storage) {
            Ok((entries, _)) => entries,
            Err(e) => {
                eprintln!(
                    "secantusd-pg: could not read {}: {e}",
                    path(storage).display()
                );
                Vec::new()
            }
        };
        let entries = Arc::new(entries);
        map.insert(
            key,
            Cluster {
                storage: Arc::downgrade(storage),
                loaded: Arc::clone(&entries),
                at_start: entries,
                pending: Arc::new(std::collections::HashSet::new()),
            },
        );
    }
    Arc::clone(&map[&key].loaded)
}

/// What the server read from the file at its start.
pub(crate) fn at_start(storage: &Arc<Storage>) -> Arc<Vec<FileEntry>> {
    loaded(storage);
    let key = Arc::as_ptr(storage) as usize;
    let map = clusters().lock().unwrap_or_else(|e| e.into_inner());
    Arc::clone(&map[&key].at_start)
}

/// The postmaster's `pending_restart` flags.
pub(crate) fn pending(storage: &Arc<Storage>) -> Arc<std::collections::HashSet<String>> {
    loaded(storage);
    let key = Arc::as_ptr(storage) as usize;
    let map = clusters().lock().unwrap_or_else(|e| e.into_inner());
    Arc::clone(&map[&key].pending)
}

/// `value` for `key` as the server compares it: its `SHOW` text where the
/// parameter is typed.
fn compared(key: &str, value: &str) -> String {
    guc_values::canonical(key, value)
        .and_then(Result::ok)
        .unwrap_or_else(|| value.to_string())
}

/// The value `key` names last in `entries`.
fn value_in(entries: &[FileEntry], key: &str) -> Option<String> {
    entries
        .iter()
        .rev()
        .find(|e| canonical_setting(&e.name) == key)
        .map(|e| e.value.clone())
}

/// The postmaster's flags after it reads `entries` (`ProcessConfigFile`):
/// a parameter only a restart changes is pending when the file now gives
/// it another value than it started with, or no longer gives the value it
/// started with; one the file does not name keeps its flag.
fn pending_after(
    before: &std::collections::HashSet<String>,
    start: &[FileEntry],
    entries: &[FileEntry],
) -> std::collections::HashSet<String> {
    let mut pending = before.clone();
    let defaults = default_settings();
    let running = |key: &str| {
        value_in(start, key)
            .map(|v| compared(key, &v))
            .or_else(|| defaults.get(key).cloned())
    };
    for e in entries {
        let key = canonical_setting(&e.name);
        if !restart_only(&key) {
            continue;
        }
        let new = value_in(entries, &key).map(|v| compared(&key, &v));
        if new != running(&key) {
            pending.insert(key);
        } else {
            pending.remove(&key);
        }
    }
    for e in start {
        let key = canonical_setting(&e.name);
        if restart_only(&key) && value_in(entries, &key).is_none() {
            pending.insert(key);
        }
    }
    pending
}

/// A parameter only a restart changes.
pub(crate) fn restart_only(key: &str) -> bool {
    matches!(context_of(key), "postmaster" | "internal")
}

/// `pg_reload_conf()`: read the file again. On an error the server keeps
/// what it had, as PostgreSQL keeps its settings when the file is bad.
pub(crate) fn reload(storage: &Arc<Storage>) -> std::io::Result<()> {
    let (entries, errors) = read(storage)?;
    if let Some(e) = errors.first() {
        return Err(std::io::Error::new(
            std::io::ErrorKind::InvalidData,
            format!(
                "{} contains errors; unaffected changes were applied: {} at line {}",
                e.file, e.message, e.line
            ),
        ));
    }
    loaded(storage);
    let key = Arc::as_ptr(storage) as usize;
    let mut map = clusters().lock().unwrap_or_else(|e| e.into_inner());
    if let Some(c) = map.get_mut(&key) {
        c.pending = Arc::new(pending_after(&c.pending, &c.at_start, &entries));
        c.loaded = Arc::new(entries);
    }
    EPOCH.fetch_add(1, std::sync::atomic::Ordering::AcqRel);
    Ok(())
}

/// `ParseConfigFp` for what this file holds: `name [=] value` lines, the
/// value a quoted string (`''` and backslash escapes) or a bare word, and
/// `#` comments.
fn parse(text: &str, file: &Arc<str>) -> (Vec<FileEntry>, Vec<FileError>) {
    let mut entries = Vec::new();
    let mut errors = Vec::new();
    for (i, raw) in text.lines().enumerate() {
        let line = i32::try_from(i + 1).unwrap_or(i32::MAX);
        match parse_line(raw) {
            Ok(Some((name, value))) => entries.push(FileEntry {
                name,
                value,
                file: Arc::clone(file),
                line,
                seq: 0,
            }),
            Ok(None) => {}
            Err(()) => errors.push(FileError {
                file: Arc::clone(file),
                line,
                message: "syntax error".into(),
                seq: 0,
            }),
        }
    }
    (entries, errors)
}

fn parse_line(raw: &str) -> Result<Option<(String, String)>, ()> {
    let s = raw.trim_start();
    if s.is_empty() || s.starts_with('#') {
        return Ok(None);
    }
    let name_end = s
        .find(|c: char| !(c.is_ascii_alphanumeric() || c == '_' || c == '.'))
        .unwrap_or(s.len());
    if name_end == 0 || s.starts_with(|c: char| c.is_ascii_digit()) {
        return Err(());
    }
    let name = s[..name_end].to_string();
    let mut rest = s[name_end..].trim_start();
    if let Some(r) = rest.strip_prefix('=') {
        rest = r.trim_start();
    }
    let (value, after) = if let Some(body) = rest.strip_prefix('\'') {
        let mut value = String::new();
        let mut chars = body.char_indices();
        let mut end = None;
        while let Some((at, c)) = chars.next() {
            match c {
                '\'' if body[at + 1..].starts_with('\'') => {
                    value.push('\'');
                    chars.next();
                }
                '\'' => {
                    end = Some(at + 1);
                    break;
                }
                '\\' => match chars.next().map(|(_, c)| c) {
                    Some('b') => value.push('\u{8}'),
                    Some('f') => value.push('\u{c}'),
                    Some('n') => value.push('\n'),
                    Some('r') => value.push('\r'),
                    Some('t') => value.push('\t'),
                    Some(c) => value.push(c),
                    None => return Err(()),
                },
                c => value.push(c),
            }
        }
        let end = end.ok_or(())?;
        (value, &body[end..])
    } else {
        let end = rest
            .find(|c: char| c.is_whitespace() || c == '#')
            .unwrap_or(rest.len());
        if end == 0 {
            return Err(());
        }
        (rest[..end].to_string(), &rest[end..])
    };
    let after = after.trim_start();
    if !(after.is_empty() || after.starts_with('#')) {
        return Err(());
    }
    Ok(Some((name, value)))
}

/// `write_auto_conf_file`: the header and the entries, in a temporary file
/// synced and renamed over the old one, the directory synced after.
fn write(storage: &Storage, entries: &[FileEntry]) -> std::io::Result<()> {
    use std::io::Write as _;
    let target = path(storage);
    let tmp = target.with_extension("conf.tmp");
    let mut text = String::from(HEADER);
    for e in entries {
        let escaped = e.value.replace('\\', "\\\\").replace('\'', "''");
        text.push_str(&format!("{} = '{escaped}'\n", e.name));
    }
    {
        let mut f = std::fs::File::create(&tmp)?;
        f.write_all(text.as_bytes())?;
        f.sync_all()?;
    }
    std::fs::rename(&tmp, &target)?;
    if let Some(dir) = target.parent() {
        std::fs::File::open(dir)?.sync_all()?;
    }
    Ok(())
}

/// Is `a` the parameter `b` names (`guc_name_compare`)?
fn same_name(a: &str, b: &str) -> bool {
    canonical_setting(a) == canonical_setting(b)
}

/// The setting `name`'s context, as `pg_settings` reports it.
pub(crate) fn context_of(key: &str) -> &'static str {
    if let Some(p) = pg15_settings::pg15_setting(key) {
        return p.context;
    }
    match key {
        "log_timezone" => "sighup",
        k if UNDUMPED_SETTINGS.contains(&k) => "postmaster",
        k if is_internal_setting(k) => "internal",
        _ => "user",
    }
}

impl PgHandler {
    /// `ALTER SYSTEM SET name = value` / `RESET name` / `RESET ALL`:
    /// `AlterSystemSetConfigFile`.
    pub(crate) fn alter_system(
        &self,
        name: Option<String>,
        value: Option<String>,
    ) -> PgWireResult<Vec<Response>> {
        self.refuse_in_transaction_block("ALTER SYSTEM")?;
        let superuser = self.is_superuser(&self.current_role_name());
        let Some(name) = name else {
            if !superuser {
                return Err(Self::user_error(
                    "42501",
                    "permission denied to perform ALTER SYSTEM RESET ALL".into(),
                ));
            }
            self.write_auto_conf(Vec::new())?;
            return Ok(vec![Response::Execution(Tag::new("ALTER SYSTEM"))]);
        };
        // A custom name is a parameter only once a placeholder for it
        // exists, which here is a value this session holds.
        let key = canonical_setting(&name);
        let known = if key.contains('.') {
            self.settings
                .lock()
                .unwrap_or_else(|e| e.into_inner())
                .contains_key(&key)
        } else {
            self.check_setting_known(&name).is_ok()
        };
        if !known {
            return Err(Self::user_error(
                "42704",
                format!("unrecognized configuration parameter \"{name}\""),
            ));
        }
        // A superuser, or a role granted ALTER SYSTEM on the parameter.
        if !self.parameter_privilege_held(
            &self.current_role_name(),
            &name.to_ascii_lowercase(),
            "ALTER SYSTEM",
            false,
        ) {
            return Err(Self::user_error(
                "42501",
                format!("permission denied to set parameter \"{name}\""),
            ));
        }
        if context_of(&key) == "internal" || DISALLOWED.contains(&key.as_str()) {
            return Err(Self::user_error(
                "55P02",
                format!("parameter \"{key}\" cannot be changed"),
            ));
        }
        if let Some(v) = &value {
            self.canonical_setting_value(&key, v)?;
        }
        let mut entries = read_auto(&self.storage).map_err(|e| self.auto_conf_error(e))?;
        entries.retain(|e| !same_name(&e.name, &name));
        if let Some(value) = value {
            entries.push(FileEntry {
                name,
                value,
                file: Arc::from(""),
                line: 0,
                seq: 0,
            });
        }
        self.write_auto_conf(entries)?;
        Ok(vec![Response::Execution(Tag::new("ALTER SYSTEM"))])
    }

    fn write_auto_conf(&self, entries: Vec<FileEntry>) -> PgWireResult<()> {
        write(&self.storage, &entries).map_err(|e| self.auto_conf_error(e))
    }

    fn auto_conf_error(&self, e: std::io::Error) -> PgWireError {
        Self::user_error(
            "58030",
            format!(
                "could not write file \"{}\": {e}",
                path(&self.storage).display()
            ),
        )
    }

    /// The server's configuration file as a new session takes it: this
    /// session's starting point.
    pub(crate) fn start_config_layer(&self) {
        let epoch = epoch();
        let loaded = loaded(&self.storage);
        *self.config_file.lock().unwrap_or_else(|e| e.into_inner()) = (epoch, loaded);
        // A backend inherits the postmaster's flags.
        *self
            .pending_restart
            .lock()
            .unwrap_or_else(|e| e.into_inner()) = (*pending(&self.storage)).clone();
    }

    /// The file's entries this session's settings come from: the last
    /// reload's, and for a parameter only a restart changes, the start's.
    pub(crate) fn file_settings_in_force(&self) -> Vec<FileEntry> {
        let start = at_start(&self.storage);
        self.config_layer()
            .iter()
            .filter(|e| !restart_only(&canonical_setting(&e.name)))
            .chain(
                start
                    .iter()
                    .filter(|e| restart_only(&canonical_setting(&e.name))),
            )
            .cloned()
            .collect()
    }

    /// The configuration file as this session last applied it.
    pub(crate) fn config_layer(&self) -> Arc<Vec<FileEntry>> {
        Arc::clone(&self.config_file.lock().unwrap_or_else(|e| e.into_inner()).1)
    }

    /// The file and line a `configuration file` setting came from.
    pub(crate) fn config_line_of(&self, key: &str) -> Option<(Arc<str>, i32)> {
        self.file_settings_in_force()
            .iter()
            .rev()
            .find(|e| canonical_setting(&e.name) == key)
            .map(|e| (Arc::clone(&e.file), e.line))
    }

    /// The SIGHUP a reload sends every backend, processed between
    /// messages: a value the file gave (or now gives) changes where the
    /// session's own source ranks no higher than the file's, in the session
    /// and in the values its open transaction would put back; a parameter
    /// only a restart changes is marked `pending_restart` instead.
    pub(crate) fn apply_config_reload(&self) {
        let epoch = epoch();
        if self.config_file.lock().unwrap_or_else(|e| e.into_inner()).0 == epoch {
            return;
        }
        let loaded = loaded(&self.storage);
        let old = {
            let mut layer = self.config_file.lock().unwrap_or_else(|e| e.into_inner());
            layer.0 = epoch;
            std::mem::replace(&mut layer.1, Arc::clone(&loaded))
        };
        if Arc::ptr_eq(&old, &loaded) {
            return;
        }
        let mut keys: Vec<String> = old
            .iter()
            .chain(loaded.iter())
            .map(|e| canonical_setting(&e.name))
            .collect();
        keys.sort();
        keys.dedup();
        let defaults = self.server_defaults();
        let in_block = self
            .in_transaction
            .load(std::sync::atomic::Ordering::Relaxed);
        for key in keys {
            let new = value_in(&loaded, &key);
            let target = match &new {
                Some(raw) => match self.canonical_setting_value(&key, raw) {
                    Ok(v) => Some((v, GucSource::ConfigFile)),
                    Err(e) => {
                        eprintln!(
                            "secantusd-pg: configuration file setting {key} = {raw} not applied: {e:?}"
                        );
                        continue;
                    }
                },
                None => defaults.get(&key).map(|v| (v.clone(), GucSource::Default)),
            };
            let Some(target) = target else { continue };
            if restart_only(&key) {
                continue;
            }
            if value_in(&old, &key) == new {
                continue;
            }
            let changed = {
                let mut settings = self.settings.lock().unwrap_or_else(|e| e.into_inner());
                if settings.source_of(&key) > GucSource::ConfigFile {
                    false
                } else {
                    let changed = settings.get(&key) != Some(&target.0);
                    settings.set_from(&key, target.0.clone(), target.1);
                    if let Some(twin) = key.strip_prefix("default_") {
                        if !in_block
                            && matches!(
                                twin,
                                "transaction_read_only"
                                    | "transaction_isolation"
                                    | "transaction_deferrable"
                            )
                        {
                            settings.insert_keeping_source(twin, target.0.clone());
                        }
                    }
                    changed
                }
            };
            if let Some((before, _)) = self
                .txn_gucs
                .lock()
                .unwrap_or_else(|e| e.into_inner())
                .get_mut(&key)
            {
                if before
                    .as_ref()
                    .is_none_or(|(_, s)| *s <= GucSource::ConfigFile)
                {
                    *before = Some(target.clone());
                }
            }
            for sp in self
                .savepoints
                .lock()
                .unwrap_or_else(|e| e.into_inner())
                .iter_mut()
            {
                if sp.settings.source_of(&key) <= GucSource::ConfigFile {
                    sp.settings.set_from(&key, target.0.clone(), target.1);
                }
            }
            if changed {
                self.note_reportable_guc(&key, &target.0);
            }
        }
        // The backend's flags come out as the postmaster's.
        *self
            .pending_restart
            .lock()
            .unwrap_or_else(|e| e.into_inner()) = (*pending(&self.storage)).clone();
    }

    /// Set or clear each parameter's `pending_restart`, as
    /// `set_config_option` does for one a restart alone changes.
    fn mark_pending_restart(&self, marks: Vec<(String, bool)>) {
        let mut set = self
            .pending_restart
            .lock()
            .unwrap_or_else(|e| e.into_inner());
        for (key, pending) in marks {
            if pending {
                set.insert(key);
            } else {
                set.remove(&key);
            }
        }
    }

    /// `pg_file_settings`: the file as it is now, each line with whether
    /// this session could apply it (a later line of the same name wins; a
    /// parameter only a restart changes cannot take a new value), as
    /// `ProcessConfigFileInternal` checks it -- which also marks such a
    /// parameter `pending_restart` in the session that asks.
    pub(crate) fn file_setting_rows(&self, def: &TableDef) -> Vec<Document> {
        let field = |c: &str| def.field_of(c).expect("column");
        let (entries, errors) = match read(&self.storage) {
            Ok(read) => read,
            Err(e) => {
                eprintln!(
                    "secantusd-pg: could not read the configuration files of {}: {e}",
                    data_directory(&self.storage).display()
                );
                return Vec::new();
            }
        };
        let mut rows: Vec<(usize, Document)> = Vec::new();
        let mut pending: Vec<(String, bool)> = Vec::new();
        // A file with an error applies nothing (`ProcessConfigFileInternal`
        // bails out before applying).
        let failed = !errors.is_empty();
        for (i, e) in entries.iter().enumerate() {
            let key = canonical_setting(&e.name);
            let superseded = entries[i + 1..]
                .iter()
                .any(|later| canonical_setting(&later.name) == key);
            let mut error = None;
            let mut applied = !superseded && !failed;
            if !superseded && !failed {
                match self.canonical_setting_value(&key, &e.value) {
                    Err(_) => {
                        applied = false;
                        error = Some("setting could not be applied");
                    }
                    Ok(v) if context_of(&key) == "postmaster" => {
                        let current = self
                            .settings
                            .lock()
                            .unwrap_or_else(|e| e.into_inner())
                            .get(&key)
                            .cloned();
                        let differs = current.as_deref() != Some(v.as_str());
                        if differs {
                            applied = false;
                            error = Some("setting could not be applied");
                        }
                        pending.push((key.clone(), differs));
                    }
                    Ok(_) => {}
                }
            }
            let mut d = Document::new();
            d.insert(field("sourcefile"), &*e.file);
            d.insert(field("sourceline"), e.line);
            d.insert(field("name"), e.name.as_str());
            d.insert(field("setting"), e.value.as_str());
            d.insert(field("applied"), applied);
            d.insert(field("error"), error.map_or(Bson::Null, Bson::from));
            rows.push((e.seq, d));
        }
        for e in &errors {
            let mut d = Document::new();
            d.insert(field("sourcefile"), &*e.file);
            d.insert(field("sourceline"), e.line);
            d.insert(field("name"), Bson::Null);
            d.insert(field("setting"), Bson::Null);
            d.insert(field("applied"), false);
            d.insert(field("error"), e.message.as_str());
            rows.push((e.seq, d));
        }
        rows.sort_by_key(|(seq, _)| *seq);
        self.mark_pending_restart(pending);
        rows.into_iter()
            .enumerate()
            .map(|(i, (_, mut d))| {
                d.insert(field("seqno"), i32::try_from(i + 1).unwrap_or(i32::MAX));
                d
            })
            .collect()
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_file_reads_back_what_alter_system_writes() {
        let text = "# Do not edit this file manually!\n\
                    # It will be overwritten by the ALTER SYSTEM command.\n\
                    application_name = 'it''s a \\\\ b'\n\
                    work_mem = '8192'\n\
                    search_path = '\"A b\", c'  # a comment\n\
                    bare 8MB\n";
        let (entries, errors) = parse(text, &Arc::from("f"));
        assert!(errors.is_empty());
        let got: Vec<_> = entries
            .iter()
            .map(|e| (e.name.as_str(), e.value.as_str(), e.line))
            .collect();
        assert_eq!(
            got,
            [
                ("application_name", "it's a \\ b", 3),
                ("work_mem", "8192", 4),
                ("search_path", "\"A b\", c", 5),
                ("bare", "8MB", 6),
            ]
        );
        let (_, errors) = parse("work_mem = 'unterminated\n= 'x'\n", &Arc::from("f"));
        assert_eq!(errors.len(), 2);
    }
}
