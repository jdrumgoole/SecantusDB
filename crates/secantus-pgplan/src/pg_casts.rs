/// Is there a built-in `pg_cast` row from `source` to `target` (any context)?
pub fn exists(source: i64, target: i64) -> bool {
    BUILTIN_CASTS
        .iter()
        .any(|(_, s, t, ..)| *s == source && *t == target)
}

/// Does PostgreSQL refuse `x::target` for an `x` of type `source`, both
/// spelled as the planner spells them? It does when both are built-in scalar
/// types, they differ, there is no `pg_cast` row between them, and neither
/// is of the string category -- `find_coercion_pathway`'s automatic I/O
/// conversion covers a cast to or from a string type, and nothing else.
/// Arrays, pseudo-types, `unknown`, user and extension types are left to
/// their own rules (answered `false`).
pub fn refused(source: &str, target: &str) -> bool {
    if source.ends_with("[]") || target.ends_with("[]") {
        return false;
    }
    let (Some(s), Some(t)) = (
        crate::pgtypes::oid_of_name(source),
        crate::pgtypes::oid_of_name(target),
    ) else {
        return false;
    };
    if s == t || s >= 16384 || t >= 16384 {
        return false;
    }
    let (Some(sc), Some(tc)) = (
        crate::funcsig::category_of_oid(s),
        crate::funcsig::category_of_oid(t),
    ) else {
        return false;
    };
    if matches!(sc, 'S' | 'P' | 'X') || matches!(tc, 'S' | 'P' | 'X') {
        return false;
    }
    if crate::user_casts::find(source, target).is_some() {
        return false;
    }
    !exists(s, t)
}
