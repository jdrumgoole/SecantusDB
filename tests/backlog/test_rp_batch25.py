def _dsn(server: Any) -> str:
    return f"host=127.0.0.1 port={server.port} dbname=postgres user=postgres"


@pytest.mark.parametrize(
    "name",
    [
        pytest.param(name, marks=pytest.mark.backlog_fixed(item), id=name)
        for name, (item, _) in sorted(SCENARIOS.items())
    ],
)
def test_scenario(name: str, rust_pg: Any) -> None:
    assert run_scenario(_dsn(rust_pg), SCENARIOS[name][1]) == EXPECTED[name]


