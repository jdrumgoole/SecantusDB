def _answer(conn: Any, sql: str) -> Any:
    try:
        cur = conn.execute(sql)
    except psycopg.Error as e:
        return ("ERR", e.sqlstate)
    if cur.description is None:
        return cur.statusmessage
    return [tuple(str(v) for v in row) for row in cur.fetchall()]


def run_scenario(dsn: str, statements: list[str]) -> list[Any]:
    with psycopg.connect(dsn, autocommit=True) as conn:
        out = [_answer(conn, s) for s in statements]
        if conn.info.transaction_status != psycopg.pq.TransactionStatus.IDLE:
            conn.execute(ROLLBACK)
        return out


def copy_scenarios(dsn: str) -> list[Any]:
    """Every COPY TO / FROM option shape, each in its own connection's
    temporary table: the data written or the rows read, or the SQLSTATE."""
    out = []
    with psycopg.connect(dsn, autocommit=True) as conn:
        for s in COPY_SETUP:
            conn.execute(s)
        for o in COPY_OUT:
            try:
                buf = b""
                with conn.cursor().copy(f"copy rpc to stdout {o}") as cp:
                    for chunk in cp:
                        buf += bytes(chunk)
                out.append((o, buf.decode()))
            except psycopg.Error as e:
                out.append((o, ("ERR", e.sqlstate)))
        for o, data in COPY_IN:
            conn.execute("truncate rpc")
            try:
                with conn.transaction():
                    if "freeze" in o:
                        conn.execute("truncate rpc")
                    with conn.cursor().copy(f"copy rpc from stdin {o}") as cp:
                        cp.write(data)
                rows = conn.execute(
                    "select a, b, c, b is null, c is null from rpc order by a"
                ).fetchall()
                out.append((o, [tuple(str(v) for v in r) for r in rows]))
            except psycopg.Error as e:
                out.append((o, ("ERR", e.sqlstate)))
        # FREEZE outside a block, and after a SAVEPOINT, is refused.
        for seq in (["truncate rpc"], ["begin", "truncate rpc", "savepoint s"]):
            for s in seq:
                conn.execute(s)
            try:
                with conn.cursor().copy("copy rpc from stdin (freeze)") as cp:
                    cp.write("3\ty\tz\n")
                out.append((str(seq), "ok"))
            except psycopg.Error as e:
                out.append((str(seq), ("ERR", e.sqlstate)))
            if conn.info.transaction_status != psycopg.pq.TransactionStatus.IDLE:
                conn.execute(ROLLBACK)
    return out


