create type mood as enum ('sad', 'ok', 'happy');
create domain posint as int check (value > 0);
create type pair as (a int, b text);
create sequence seq1 start 5 increment 2;
create table p (id int primary key, name varchar(20) not null unique, m mood default 'ok', d posint, created timestamptz default now());
create table c (id bigserial primary key, pid int references p(id) on delete cascade, amount numeric(10,2) not null default 0 check (amount >= 0), tags text[], meta jsonb);
create table ident (id int generated always as identity, g int generated always as (id * 2) stored, note text);
create index c_pid_idx on c (pid);
create unique index p_lower_name on p (lower(name));
create view pv as select id, name from p where id > 0;
create materialized view pmv as select pid, count(*) as n from c group by pid;
create function add1(x int) returns int language sql immutable as $$ select x + 1 $$;
create function trg() returns trigger language plpgsql as $$ begin new.name := upper(new.name); return new; end $$;
create trigger p_upper before insert on p for each row execute function trg();
create table parted (k int, v text) partition by range (k);
create table parted_1 partition of parted for values from (0) to (100);
create table base (x int);
create table child (y int) inherits (base);
comment on column p.name is 'the name';
comment on function add1(int) is 'adds one';
create role rp26_reader;
grant select on p to rp26_reader;
alter table c enable row level security;
create policy cpol on c for select using (amount > 0);
