"""Regenerate ``crates/secantus-pgplan/src/pg_function_names.rs``.

The Rust PostgreSQL server answers a call to a function PostgreSQL has never
heard of with ``42883 function nosuch(integer) does not exist`` and a call to
one it merely has not implemented yet with ``0A000``. Telling the two apart
needs PostgreSQL's own list of function names, which this script reads from a
live server: every ``pg_proc`` name in ``pg_catalog`` plus the names the
``hstore`` and ``postgis`` extensions add (the two extensions the server
emulates).

Run against the reference PostgreSQL (16.x) with both extensions installed::

    uv run python tools/gen_pg_function_names.py --dsn "host=127.0.0.1 dbname=postgres"
"""

from __future__ import annotations

import argparse
import pathlib
import signal
import sys

import psycopg

QUERY = """
select distinct p.proname
from pg_proc p
join pg_namespace n on n.oid = p.pronamespace
where n.nspname = 'pg_catalog'
union
select distinct p.proname
from pg_depend d
join pg_extension e on e.oid = d.refobjid and d.refclassid = 'pg_extension'::regclass
join pg_proc p on p.oid = d.objid and d.classid = 'pg_proc'::regclass
where e.extname = any(%s)
"""

HEADER = """\
//! Every function name PostgreSQL {version} knows: `pg_catalog` plus the
//! `hstore` and `postgis` extensions. GENERATED by
//! `tools/gen_pg_function_names.py` -- regenerate, never edit.
//!
//! A call to a name that is not here is `42883 function nosuch(integer) does
//! not exist`, as PostgreSQL reports it; a call to a name that IS here but
//! has no implementation stays an honest `0A000`.

/// Whether PostgreSQL (or one of the two emulated extensions) has a function
/// of this name, whatever its argument types.
pub fn is_known_function(name: &str) -> bool {{
    NAMES.binary_search(&name).is_ok()
}}

/// Byte-sorted, for the binary search.
static NAMES: &[&str] = &[
"""


def main(argv: list[str] | None = None) -> int:
    signal.signal(signal.SIGINT, signal.SIG_DFL)
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--dsn", default="host=127.0.0.1 port=5432 dbname=postgres")
    parser.add_argument(
        "--out",
        type=pathlib.Path,
        default=pathlib.Path(__file__).resolve().parents[1]
        / "crates/secantus-pgplan/src/pg_function_names.rs",
    )
    parser.add_argument("--extensions", nargs="*", default=["hstore", "postgis"])
    args = parser.parse_args(argv)
    with psycopg.connect(args.dsn, autocommit=True) as conn:
        installed = {row[0] for row in conn.execute("select extname from pg_extension")}
        missing = set(args.extensions) - installed
        if missing:
            print(
                f"extensions not installed on the reference server: {sorted(missing)}",
                file=sys.stderr,
            )
            return 1
        version = conn.execute("show server_version").fetchone()[0]
        names = sorted(
            (row[0] for row in conn.execute(QUERY, (args.extensions,))),
            key=lambda n: n.encode(),
        )
    lines = [HEADER.rstrip("\n").format(version=version.split()[0])]
    lines.extend(f"    {name!r},".replace("'", '"') for name in names)
    lines.append("];\n")
    args.out.write_text("\n".join(lines))
    print(f"wrote {len(names)} names to {args.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
