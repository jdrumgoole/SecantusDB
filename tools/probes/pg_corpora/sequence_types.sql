# CREATE / ALTER SEQUENCE AS <type> and CACHE, the type's bounds and their errors, ALTER's bound checks, pg_sequences, and identity / serial sequence types.
CREATE table pss (id int generated by default as identity (start 5 increment 2), s serial, b bigserial, ss smallserial, v int)
CREATE sequence pss_q increment -1 cycle
CREATE sequence pss_c as smallint cache 10
SELECT nextval('pss_q')
SELECT schemaname, sequencename, data_type, start_value, min_value, max_value, increment_by, cycle, cache_size, last_value from pg_sequences where sequencename like 'pss%' order by sequencename
SELECT seqtypid::regtype, seqmax, seqmin, seqcache from pg_sequence where seqrelid = 'pss_c'::regclass
SELECT sequence_name, data_type, minimum_value, maximum_value from information_schema.sequences where sequence_name like 'pss%' order by 1
CREATE sequence pss_x as smallint maxvalue 40000
CREATE sequence pss_x as text
CREATE sequence pss_x cache 0
CREATE sequence pss_x minvalue -40000 as smallint
CREATE sequence pss_y as smallint
SELECT nextval('pss_y'), setval('pss_y', 32767)
SELECT nextval('pss_y')
ALTER sequence pss_y as int
SELECT seqmax, seqtypid::regtype from pg_sequence where seqrelid = 'pss_y'::regclass
ALTER sequence pss_y as smallint maxvalue 100
CREATE sequence pss_z start 5
ALTER sequence pss_z minvalue 6
ALTER sequence pss_z maxvalue 4
SELECT setval('pss_z', 50)
ALTER sequence pss_z maxvalue 40
ALTER sequence pss_z maxvalue 60 minvalue 70
ALTER sequence pss_z restart with 55
SELECT nextval('pss_z')
DROP TABLE pss
DROP SEQUENCE pss_q
DROP SEQUENCE pss_c
DROP SEQUENCE pss_y
DROP SEQUENCE pss_z
