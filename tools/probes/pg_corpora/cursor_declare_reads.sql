# A DECLARE's query is planned as a statement of its own: a temp table, a
# subquery, a TABLESAMPLE; its reads are checked for privileges and RLS.
BEGIN
CREATE TEMP TABLE b5c_tmp (a int)
INSERT INTO b5c_tmp VALUES (5), (6)
DECLARE t1 CURSOR FOR SELECT a FROM b5c_tmp ORDER BY a
FETCH ALL FROM t1
DECLARE t2 CURSOR FOR SELECT a FROM pg_temp.b5c_tmp
FETCH 1 FROM t2
SELECT a FROM b5c_tmp TABLESAMPLE SYSTEM (100) ORDER BY a
DECLARE s1 CURSOR FOR SELECT a FROM b5c_st WHERE a IN (SELECT a FROM b5c_su) ORDER BY a
FETCH ALL FROM s1
DECLARE s2 CURSOR FOR SELECT a, (SELECT max(c) FROM b5c_su) FROM b5c_st WHERE a < 3 ORDER BY a
FETCH ALL FROM s2
DECLARE s3 CURSOR FOR SELECT a FROM b5c_st WHERE NOT EXISTS (SELECT 1 FROM b5c_su WHERE b5c_su.a = b5c_st.a) AND a < 5 ORDER BY a
FETCH ALL FROM s3
SAVEPOINT p
DECLARE t1 CURSOR FOR SELECT 1
ROLLBACK TO p
FETCH 1 FROM t1
ROLLBACK
# A cursor declared with neither SCROLL nor NO SCROLL scans backward when
# its plan can.
BEGIN
DECLARE d1 CURSOR FOR SELECT * FROM b5c_st ORDER BY a
FETCH 2 FROM d1
FETCH BACKWARD 1 FROM d1
DECLARE d2 CURSOR FOR VALUES (1), (2), (3)
FETCH 2 FROM d2
FETCH BACKWARD 1 FROM d2
DECLARE d3 CURSOR FOR SELECT * FROM generate_series(1, 3)
FETCH 2 FROM d3
FETCH BACKWARD 1 FROM d3
DECLARE d4 CURSOR FOR SELECT a FROM (SELECT a FROM b5c_st LIMIT 3) s
FETCH 2 FROM d4
FETCH BACKWARD 1 FROM d4
DECLARE d5 CURSOR FOR SELECT count(*) FROM b5c_st ORDER BY 1
FETCH 1 FROM d5
FETCH BACKWARD 1 FROM d5
SAVEPOINT p
DECLARE n1 CURSOR FOR SELECT 1
FETCH 1 FROM n1
FETCH BACKWARD 1 FROM n1
ROLLBACK TO p
DECLARE n2 CURSOR FOR SELECT count(*) FROM b5c_st
FETCH 1 FROM n2
FETCH BACKWARD 1 FROM n2
ROLLBACK TO p
DECLARE n3 CURSOR FOR SELECT DISTINCT b FROM b5c_st
FETCH 1 FROM n3
FETCH BACKWARD 1 FROM n3
ROLLBACK TO p
DECLARE n4 CURSOR FOR SELECT * FROM b5c_st, b5c_su
FETCH 1 FROM n4
FETCH BACKWARD 1 FROM n4
ROLLBACK TO p
DECLARE n5 CURSOR FOR SELECT generate_series(1, 3)
FETCH 1 FROM n5
FETCH BACKWARD 1 FROM n5
ROLLBACK TO p
