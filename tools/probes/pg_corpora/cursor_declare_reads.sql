# A FETCH that fails leaves its cursor failed; cursor_to_xml reads backward
# with a negative count.
BEGIN
DECLARE f1 NO SCROLL CURSOR FOR SELECT a FROM b5c_st ORDER BY a
FETCH 1 FROM f1
SAVEPOINT p
FETCH BACKWARD 1 FROM f1
ROLLBACK TO p
FETCH 1 FROM f1
SELECT cursor_to_xml('f1', 1, false, true, '')
CLOSE f1
DECLARE x1 SCROLL CURSOR FOR SELECT a FROM b5c_st ORDER BY a
SELECT cursor_to_xml('x1', 3, false, true, '')
SELECT cursor_to_xml('x1', -2, false, true, '')
SELECT cursor_to_xml('x1', -5, false, true, '')
SELECT cursor_to_xml('x1', 1, false, true, '')
ROLLBACK
# Privileges and row-level security reach a DECLARE's and a TABLESAMPLE's
# reads.
BEGIN
ALTER TABLE b5c_rls ENABLE ROW LEVEL SECURITY
CREATE POLICY b5c_p ON b5c_rls FOR SELECT USING (owner = current_user)
SET ROLE b5c_r
SELECT a FROM b5c_rls ORDER BY a
SELECT a FROM b5c_rls TABLESAMPLE SYSTEM (100) ORDER BY a
DECLARE r1 CURSOR FOR SELECT a FROM b5c_rls
FETCH ALL FROM r1
DECLARE c1 CURSOR FOR SELECT a FROM b5c_col ORDER BY a
FETCH ALL FROM c1
SAVEPOINT p
DECLARE c2 CURSOR FOR SELECT b FROM b5c_col
ROLLBACK TO p
SELECT x.b FROM b5c_col x TABLESAMPLE SYSTEM (100)
ROLLBACK TO p
SELECT x.a FROM b5c_col x TABLESAMPLE SYSTEM (100) ORDER BY 1
DECLARE c3 CURSOR FOR SELECT * FROM b5c_st
ROLLBACK TO p
SELECT * FROM b5c_st TABLESAMPLE BERNOULLI (100)
ROLLBACK
DROP TABLE b5c_st
DROP TABLE b5c_su
DROP TABLE b5c_col
DROP TABLE b5c_rls
DROP ROLE b5c_r
