DROP TABLE IF EXISTS tm_t CASCADE
DROP TABLE IF EXISTS tm_id CASCADE
DROP TABLE IF EXISTS tm_id2 CASCADE
DROP DOMAIN IF EXISTS tm_d CASCADE
DROP TYPE IF EXISTS tm_e CASCADE
CREATE DOMAIN tm_d AS varchar(5)
CREATE TYPE tm_e AS ENUM ('a')
CREATE TABLE tm_t (a interval(1), b interval day to minute, c time(2), d timestamptz, e bit(3), f varbit, g numeric(6,2), h char(1), i text COLLATE "C", j int[], k tm_d, l tm_e, m float8, n smallint, o bigint, p numeric, q varchar(4), r bytea, s bool, t date, u real, z int DEFAULT 3 NOT NULL, zz int GENERATED ALWAYS AS (z * 2) STORED)
CREATE TABLE tm_id (id int GENERATED BY DEFAULT AS IDENTITY (START 5 INCREMENT 2), v int)
CREATE TABLE tm_id2 (id bigint GENERATED BY DEFAULT AS IDENTITY (START 10 MINVALUE 5 MAXVALUE 11 CYCLE), v int)
