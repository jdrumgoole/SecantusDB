DROP VIEW IF EXISTS b45v1, b45v2, b45v3, b45v4, b45v5, b45v6, b45v7, b45v8, b45v9, b45v10, b45v11, b45v12
DROP TABLE IF EXISTS b45r
CREATE TABLE b45r (a int, d date, ts timestamp, tz timestamptz, t text, n numeric)
CREATE VIEW b45v1 AS SELECT a FROM b45r WHERE d < ts
CREATE VIEW b45v2 AS SELECT a FROM b45r WHERE tz > d
CREATE VIEW b45v3 AS SELECT sum(a) OVER (ORDER BY a RANGE BETWEEN 1 PRECEDING AND CURRENT ROW) FROM b45r
CREATE VIEW b45v4 AS WITH c AS MATERIALIZED (SELECT a FROM b45r) SELECT a FROM c
CREATE VIEW b45v5 AS SELECT md5(t), initcap(t), split_part(t, ',', 2) FROM b45r
CREATE VIEW b45v6 AS SELECT a FROM b45r WHERE ts = '2020-01-01'::date
CREATE VIEW b45v8 AS WITH c AS NOT MATERIALIZED (SELECT a FROM b45r) SELECT a FROM c
CREATE VIEW b45v9 AS SELECT sum(a) OVER (ORDER BY n RANGE BETWEEN 1 PRECEDING AND 2 FOLLOWING) FROM b45r
CREATE VIEW b45v10 AS SELECT a FROM b45r WHERE d >= tz AND ts <> tz
CREATE VIEW b45v11 AS SELECT sum(a) OVER (ORDER BY n RANGE BETWEEN 1.5 PRECEDING AND CURRENT ROW) FROM b45r
CREATE VIEW b45v12 AS SELECT sum(a) OVER (ORDER BY d RANGE BETWEEN '1 day'::interval PRECEDING AND CURRENT ROW) FROM b45r
