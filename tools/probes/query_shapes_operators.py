def _raw(_id: int, type_byte: bytes, payload: bytes, field: bytes = b"v") -> RawBSONDocument:
    """A document `{_id, <field>: <value>}` whose value is a type pymongo cannot write."""
    body = b"\x10_id\x00" + struct.pack("<i", _id) + type_byte + field + b"\x00" + payload
    return RawBSONDocument(struct.pack("<i", len(body) + 5) + body + b"\x00")


def _cstr(s: str) -> bytes:
    data = s.encode() + b"\x00"
    return struct.pack("<i", len(data)) + data


def _symbol(_id: int, s: str) -> RawBSONDocument:
    return _raw(_id, b"\x0e", _cstr(s))


def _undefined(_id: int) -> RawBSONDocument:
    return _raw(_id, b"\x06", b"")


def _dbpointer(_id: int) -> RawBSONDocument:
    return _raw(_id, b"\x0c", _cstr("db.c") + bytes.fromhex("64b7f9a2c1d2e3f4a5b6c7d8"))


def _raw_filter(field: str, type_byte: bytes, payload: bytes) -> RawBSONDocument:
    """A filter `{<field>: <value>}` holding a type pymongo cannot write."""
    body = type_byte + field.encode() + b"\x00" + payload
    return RawBSONDocument(struct.pack("<i", len(body) + 5) + body + b"\x00")


def _raw_op(field: str, op: str, type_byte: bytes, payload: bytes) -> RawBSONDocument:
    """A filter `{<field>: {<op>: <value>}}` holding a type pymongo cannot write."""
    inner = type_byte + op.encode() + b"\x00" + payload
    inner = struct.pack("<i", len(inner) + 5) + inner + b"\x00"
    body = b"\x03" + field.encode() + b"\x00" + inner
    return RawBSONDocument(struct.pack("<i", len(body) + 5) + body + b"\x00")


